import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

// Cover the entire installed production closure conservatively. This includes
// packages that either bundle may tree-shake, avoiding a fragile minifier-based
// guess about which copyright notices are required.
export function writeThirdPartyNotices(root = process.cwd()) {
  const visited = new Set();
  const packages = new Map();
  function visit(manifest, include) {
    const file = realpathSync(manifest);
    if (visited.has(file)) return;
    visited.add(file);
    const pkg = JSON.parse(readFileSync(file, 'utf8'));
    if (include) {
      const legalFiles = readdirSync(dirname(file), { withFileTypes: true })
        .filter((entry) => entry.isFile() && /^(licen[cs]e|copying|notice|copyright)(\.|$)/i.test(entry.name))
        .map((entry) => entry.name).sort();
      if (legalFiles.length === 0) throw new Error(`Missing license text for ${pkg.name}@${pkg.version}`);
      const notices = legalFiles.map((name) => ({ name, text: readFileSync(join(dirname(file), name), 'utf8') }));
      const identity = `${pkg.name}@${pkg.version}`;
      const previous = packages.get(identity);
      if (previous && JSON.stringify(previous) !== JSON.stringify(notices)) throw new Error(`Conflicting notices for ${identity}`);
      packages.set(identity, notices);
    }
    const resolver = createRequire(file);
    for (const dependency of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies }).sort()) {
      const candidate = resolver.resolve.paths(dependency)?.map((base) => join(base, dependency, 'package.json')).find(existsSync);
      if (candidate) visit(candidate, true);
      else if (!(dependency in (pkg.optionalDependencies ?? {}))) throw new Error(`Missing installed production dependency: ${dependency}`);
    }
  }
  visit(resolve(root, 'package.json'), false);
  const sections = [...packages.entries()].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
    .map(([identity, notices]) => `## ${identity}\n\n${notices.map(({ name, text }) => `### ${name}\n\n~~~~text\n${text}${text.endsWith('\n') ? '' : '\n'}~~~~\n`).join('\n')}`);
  const content = `# Third-party notices\n\nGenerated by \`node scripts/generate-third-party-notices.mjs\` from the installed production dependency closure resolved by the committed pnpm lockfile. Includes packages used by either bundle and conservatively includes production dependencies that may be tree-shaken. Build-only dependencies are excluded. Full supplied license and copyright notice files are preserved below. Regenerate after dependency changes; packaging regenerates this file automatically.\n\nPackages: ${packages.size}.\n\n${sections.join('\n')}`;
  writeFileSync(resolve(root, 'THIRD_PARTY_NOTICES.md'), content);
  return packages.size;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  console.log(`Generated THIRD_PARTY_NOTICES.md for ${writeThirdPartyNotices()} production packages.`);
}
